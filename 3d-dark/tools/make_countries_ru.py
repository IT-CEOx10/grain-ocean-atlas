def main():
    topo = json.load(open(os.path.join(ROOT, "data", "geo", "countries-110m.json"), encoding="utf-8"))
    known = {}
    for g in topo["objects"]["countries"]["geometries"]:
        if g.get("id") is not None:
            known[str(g["id"])] = g["properties"].get("name")

    out = {}
    problems = []
    seen_iso = {}
    for name, iso, lat, lon, en in DATA:
        if iso is not None and iso not in known:
            problems.append("нет в topojson: %s -> %s" % (name, iso))
        if iso is not None and iso in seen_iso:
            problems.append("iso %s задан дважды: %s и %s" % (iso, seen_iso[iso], name))
        if iso is not None:
            seen_iso[iso] = name
        if not (-90 <= lat <= 90) or not (-180 <= lon <= 180):
            problems.append("координаты вне диапазона: %s" % name)
        out[name] = {"iso": iso, "lat": lat, "lon": lon, "en": en}

    path = os.path.join(ROOT, "data", "countries_ru.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1, sort_keys=True)
        f.write("\n")

    print("записано записей: %d -> %s" % (len(out), path))
    print("без iso (нет в world-atlas 110m): %d" % sum(1 for v in out.values() if v["iso"] is None))
    if problems:
        print("ПРОБЛЕМЫ:")
        for p in problems:
            print("  " + p)
    else:
        print("проблем нет")


if __name__ == "__main__":
    main()
